// Builds a single Cloudflare Worker from files stored in this GitHub repository.
// Run by Cloudflare's remote build service when Git integration is enabled.
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
const worker=readFileSync("src/worker.js","utf8");
const files={"/": "public/index.html", "/admin": "public/admin.html", "/student": "public/student.html"};
const pages=Object.fromEntries(Object.entries(files).map(([key, file]) => [key,readFileSync(file,"utf8")]));
const adminEnhancements=readFileSync("src/admin-v2.js","utf8");
if(!pages["/admin"].includes("/*__MTI_ADMIN_V2__*/"))throw new Error("Admin enhancement injection point missing");
const rosterUI=readFileSync("src/roster-review-ui.js","utf8");
const pathwayAdmin=readFileSync("src/pathway-admin-ui.js","utf8");
const yearAdmin=readFileSync("src/year-admin-ui.js","utf8");
const courseCards=readFileSync("src/course-cards-ui.js","utf8");
const aiEditor=readFileSync("src/ai-editor-ui.js","utf8");
const unassignUI=readFileSync("src/unassign-ui.js","utf8");
pages["/admin"]=pages["/admin"].replace("/*__MTI_ADMIN_V2__*/",adminEnhancements+"\n"+rosterUI+"\n"+pathwayAdmin+"\n"+yearAdmin+"\n"+courseCards+"\n"+aiEditor+"\n"+unassignUI);
const marker="const STATIC = {};";
if(!worker.includes(marker))throw new Error("MTI asset build marker not found");
mkdirSync("dist",{recursive:true});
const curriculumImporter=readFileSync("src/curriculum-import.js","utf8");
const reviewAPI=readFileSync("src/roster-review-api.js","utf8").replace("export default {","const ROSTER_APP = {");
const notifications=readFileSync("src/progression-notifications.js","utf8");
const pathway=readFileSync("src/nine-lesson-pathway.js","utf8").replace("export default {","const YEAR_LEGACY_APP = {");
const yearProgress=readFileSync("src/year-progress.js","utf8").replace("export default {","const AI_BASE_APP = {");
const aiServices=readFileSync("src/ai-edit-materials.js","utf8").replace("export default {","const UNASSIGN_PREV_APP = {");
const unassignService=readFileSync("src/unassign-assignments.js","utf8");
const baseWorker=worker.replace("export default {","const MTI_APP = {");
if(baseWorker===worker)throw new Error("MTI Worker export marker missing");
if(!reviewAPI.includes("const ROSTER_APP = {"))throw new Error("Roster API wrapper marker missing");
if(!pathway.includes("const YEAR_LEGACY_APP = {"))throw new Error("Legacy pathway wrapper missing");
writeFileSync("dist/worker.js",baseWorker.replace(marker,"const STATIC = "+JSON.stringify(pages)+";")+"\n"+curriculumImporter+"\n"+notifications+"\n"+reviewAPI+"\n"+pathway+"\n"+yearProgress+"\n"+aiServices+"\n"+unassignService,"utf8");
console.log("Built MTI Cloudflare Worker from GitHub sources");
